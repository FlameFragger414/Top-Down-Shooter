CELL_W, CELL_H = 6, 8
COLS, ROWS = 16, 4


def build_atlas():
    cv = Canvas(COLS * CELL_W, ROWS * CELL_H)
    white = (255, 255, 255, 255)
    for i in range(64):
        ch = chr(32 + i)
        rows = G.get(ch)
        if rows is None:
            continue
        cx = (i % COLS) * CELL_W
        cy = (i // COLS) * CELL_H
        for ry, bits in enumerate(rows):
            for rx in range(5):
                if bits & (1 << (4 - rx)):
                    cv.px(cx + rx, cy + ry, white)
    return cv
